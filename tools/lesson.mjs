const HEADS = ['ПРИЁМ', 'ПРИЕМ', 'ГЕРОЙ', 'СИТУАЦИЯ', 'ДИАЛОГ', 'РАЗБОР', 'ФРАЗЫ', 'ЗАДАНИЕ', 'ВОПРОСЫ', 'ПРИВЫЧКА', 'ВЕЧЕРНИЙ ВОПРОС'];
const strip = s => String(s || '').replace(/\*\*|__|^#+\s*/gm, '').replace(/\r/g, '');
export function blocks(text) {
  const t = strip(text); const re = new RegExp('^[ \\t]*(' + HEADS.join('|') + ')[ \\t]*:[ \\t]*', 'gim'); const marks = []; let m;
  while ((m = re.exec(t))) marks.push({ h: m[1].toUpperCase().replace('ПРИЕМ', 'ПРИЁМ'), i: m.index, e: re.lastIndex });
  const out = {}; marks.forEach((k, n) => { if (!(k.h in out)) out[k.h] = t.slice(k.e, n + 1 < marks.length ? marks[n + 1].i : t.length).trim(); });
  return out;
}
const one = x => String(x || '').replace(/\s+/g, ' ').trim();
const list = x => String(x || '').split('\n').map(l => l.replace(/^\s*(?:[-•–—*]|\d+[.)])\s*/, '').trim()).filter(Boolean);
const yo = s => String(s || '').toLowerCase().replace(/ё/g, 'е');
const words = s => yo(s).replace(/[^а-яa-z0-9 ]+/g, ' ').split(/\s+/).filter(w => w.length > 2);
const cyr = t => { const l = (t.match(/[a-zа-яё]/gi) || []).length; return l ? (t.match(/[а-яё]/gi) || []).length / l : 1; };
// Насколько цитата совпадает с какой-то репликой: доля слов цитаты, встречающихся в реплике
const overlap = (q, line) => { const a = words(q), b = new Set(words(line)); return a.length ? a.filter(w => b.has(w)).length / a.length : 0; };

const stem = n => yo(n).slice(0, Math.max(2, n.length <= 4 ? n.length - 1 : n.length - 2)); // основа имени: «Ольга» → «оль», «Ольгу» тоже подходит
const LECTURE = /сегодня (мы )?(поговорим|обсудим|разберем)|в этом (уроке|диалоге)|тема (нашего|этого)|давай(те)? (попробуем|обсудим|разберем)|как думаете, стоит ли/;
const UNSAFE = /ультиматум|уволь(ся|тесь)|разорви|брось (его|ее)|накричи|отомсти|выскажи (ему|ей)? ?вс[её]|скажи (ему|ей)? ?вс[её], что думаешь|надави|дави на|вызови (у него |у нее )?ревност|обмани|соври|притворись|манипулир|игнорируй (его|ее) (несколько|целый)|пригрози/;
const GENERALIZE = /ты (всегда|никогда)|вы (всегда|никогда)|вечно ты/;
const OPEN_Q = /^(как|что|чт[оа]|какой|какая|какое|какие|каким|какую|почему|зачем|расскажи|расскажите|чем|когда|где|в как|о ч[её]м|с кем|кому|кто|откуда|сколько|опиши|вспомни|представь)/;
const VY = /(^|[^а-я])(вы|вам|вас|ваш|ваша|ваше|ваши|вашего|вашей|вашим)([^а-я]|$)/;
const VY_VERB = /[а-я]{2,}(ите|итесь|айте|айтесь|ьте|ьтесь|йте|йтесь)([^а-я]|$)/; // «откажитесь», «подумайте» — повелительное на «вы»
const DEADLINE = /\d|минут|секунд|час|один раз|два раза|три раза|сегодня|до вечера|за день|в течение|завтра/;

/* «Слабо: «…» → Лучше: «…» — почему» → вид, который рисуют приложение и бот: «Слабо: «…» → Лучше: «…» (почему)» */
export function normPair(x) {
  const m = x.match(/Слабо:?\s*(?:«([^»]+)»|"([^"]+)"|(.+?))\s*(?:→|->|—>|➜)\s*Лучше:?\s*(?:«([^»]+)»|"([^"]+)"|(.+?))\s*(?:[—–-]\s+(.+?)|\((.+)\))?\.?$/i);
  if (!m) return x;
  const a = (m[1] || m[2] || m[3] || '').trim(), b = (m[4] || m[5] || m[6] || '').trim(), why = (m[7] || m[8] || '').trim();
  return `Слабо: «${a}» → Лучше: «${b}»` + (why ? ` (${why.replace(/[()]/g, '')})` : '');
}
/* Жёсткие ошибки (урок не принимается) и мягкие (снижают оценку, уходят подсказкой в следующую попытку) */
export function checkLessonV2(txt, { day = 1, safe = () => true } = {}) {
  const b = blocks(txt); const hard = [], soft = [];
  const [heroDef, otherDef] = pairFor(day);
  const technique = one(b['ПРИЁМ']).replace(/[«»"]/g, ''), hero = (one(b['ГЕРОЙ']).match(/[А-ЯЁA-Z][а-яёa-z]+/) || [heroDef])[0];
  const situation = one(b['СИТУАЦИЯ']);
  const rawDialog = list(b['ДИАЛОГ']).filter(l => !/^\(.*\)$/.test(l) && !/^[-–—.\s…]+$/.test(l));
  const parsed = rawDialog.map(l => { const m = l.match(/^([А-ЯЁA-Z][а-яёa-z]+(?:\s[А-ЯЁ][а-яё]+)?)\s*:\s*(.+)$/); return m ? { who: m[1], say: m[2].trim() } : null; });
  const dialog = parsed.filter(Boolean);
  const speakers = [...new Set(dialog.map(x => x.who))];
  const breakdown = list(b['РАЗБОР']).slice(0, 5);
  const phrases = list(b['ФРАЗЫ']).map(x => x.replace(/^[«"]|[»"]$/g, '').trim()).filter(x => x.length >= 8).slice(0, 4);
  const task = one(b['ЗАДАНИЕ']), questions = list(b['ВОПРОСЫ']).slice(0, 3), habit = one(b['ПРИВЫЧКА']), evening = one(b['ВЕЧЕРНИЙ ВОПРОС']);

  // Структура
  if (situation.length < 40 || situation.length > 450) hard.push('ситуация слишком короткая или длинная');
  if (dialog.length < 6) hard.push('в диалоге меньше 6 реплик формата «Имя: текст»');
  if (parsed.filter(x => !x).length > 1) hard.push('в диалоге есть строки без имени говорящего (обрывки или авторский текст)');
  if (speakers.length !== 2) hard.push(`в диалоге должно быть ровно 2 собеседника, а их ${speakers.length}`);
  const other = speakers.find(s => s !== hero) || otherDef;
  if (speakers.length === 2 && !speakers.includes(hero)) hard.push(`герой «${hero}» не говорит в диалоге`);
  if (speakers.length === 2 && !speakers.every(s => yo(situation).includes(stem(s)))) hard.push('не оба собеседника названы в ситуации');
  for (let i = 2; i < dialog.length; i++) if (dialog[i].who === dialog[i - 1].who && dialog[i].who === dialog[i - 2].who) { hard.push('один человек говорит три реплики подряд'); break; }
  const heroLines = dialog.filter(x => x.who === hero);
  if (heroLines.length < 3) hard.push('у героя меньше 3 реплик');
  if (dialog.some(x => x.say.length > 260)) soft.push('слишком длинная реплика (больше 260 знаков)');
  if (dialog.some(x => LECTURE.test(yo(x.say)))) hard.push('диалог-лекция: разговор о теме урока вместо сцены');

  // Разбор опирается на диалог
  const pair = breakdown.find(x => /слабо/i.test(x) && /лучше/i.test(x) && /→|->|—>|➜/.test(x));
  if (!pair) hard.push('нет пары «Слабо: … → Лучше: …»');
  const cites = breakdown.filter(x => x !== pair).map(x => (x.match(/«([^»]{6,})»/) || [])[1]).filter(Boolean);
  const grounded = cites.filter(c => heroLines.some(l => overlap(c, l.say) >= 0.7));
  if (grounded.length < 2) hard.push('разбор не цитирует реальные слова героя из диалога (нужно минимум 2 точные цитаты)');
  if (breakdown.length < 3) hard.push('в разборе меньше 3 пунктов');

  // Фразы, задание, вопросы
  if (phrases.length < 3) hard.push('меньше 3 готовых фраз');
  if (phrases.some(p => speakers.some(s => yo(p).includes(yo(s))))) soft.push('в готовых фразах есть имена героев — их нельзя взять себе слово в слово');
  if (phrases.some(p => p.split(/\s+/).length > 18)) soft.push('готовая фраза длиннее 18 слов');
  if (task.length < 25 || task.length > 320) hard.push('задание слишком короткое или длинное');
  if (!DEADLINE.test(yo(task))) hard.push('в задании нет числа или срока');
  if (/^(запиши|напиши список|подумай)/.test(yo(task)) && !/(скажи|спроси|попроси|предложи|ответь|позвони|напиши (сообщение|письмо))/.test(yo(task))) soft.push('задание только «на бумаге», а нужно действие в разговоре');
  const open = questions.filter(q => OPEN_Q.test(yo(q)));
  if (questions.length < 3) hard.push('меньше 3 вопросов'); else if (open.length < 2) soft.push('вопросы закрытые (на «да/нет»), нужны открытые');
  if (habit.length < 10) soft.push('нет привычки'); if (evening.length < 10) soft.push('нет вечернего вопроса');
  if ([task, ...questions, habit, evening].some(x => VY.test(yo(x)) || VY_VERB.test(yo(x)))) soft.push('обращение к читателю на «вы», а нужно на «ты»');

  // Безопасность и язык
  const all = [situation, ...dialog.map(x => x.say), ...breakdown, ...phrases, task, ...questions, habit, evening].join(' ');
  if (UNSAFE.test(yo(all))) hard.push('небезопасный совет (давление, ультиматум, ложь или «выскажи всё»)');
  if (heroLines.some(l => GENERALIZE.test(yo(l.say)))) soft.push('герой обобщает «ты всегда/никогда» — это обвинение, а не приём');
  if (cyr(all) < 0.85) hard.push('много латиницы'); if (!safe(all)) hard.push('запрещённые слова или тема');
  if (!technique || technique.length < 4) soft.push('не назван приём');

  // Оценка формата 0–10
  let q = 10 - soft.length * 1.5 - hard.length * 3;
  if (grounded.length >= 3) q += 0.5; if (dialog.length >= 7 && dialog.length <= 10) q += 0.5;
  q = Math.max(0, Math.min(10, Math.round(q * 10) / 10));

  return {
    ok: hard.length === 0, hard, soft, format: q,
    lesson: { technique, hero, partner: other, situation, dialog: dialog.slice(0, 12).map(x => `${x.who}: ${x.say}`), breakdown: breakdown.map(x => x === pair ? normPair(x) : x), phrases: phrases.slice(0, 3), task, questions, habit, evening }
  };
}

/* ---------- Оценка коуча-психолога ---------- */
export const CRITERIA = ['ЛОГИКА', 'РЕАЛИЗМ', 'ПРИЁМ', 'БЕЗОПАСНОСТЬ', 'ПОЛЬЗА'];
export const judgePrompt = (t, L) => `Ты — строгий рецензент: опытный психолог-консультант и коуч по коммуникации. Оцени мини-урок для взрослых, которые волнуются в общении. Тема: «${t.topic}».

Оцени каждый критерий целым числом от 1 до 10 (10 — нечего улучшать, 6 — заметные проблемы, 3 — урок вредный или бессвязный):
ЛОГИКА — ситуация и диалог согласованы: понятно, кто кого о чём просит, роли не путаются, каждая реплика отвечает на предыдущую.
РЕАЛИЗМ — так говорят живые люди, собеседник реагирует естественно, нет канцелярита и лекций.
ПРИЁМ — заявленный приём («${L.technique || 'не назван'}») реально виден в словах героя, назван корректно, разбор объясняет его верно.
БЕЗОПАСНОСТЬ — нет манипуляций, давления, вызова чувства вины, обесценивания, диагнозов; задание посильно и безопасно для тревожного новичка.
ПОЛЬЗА — фразы и задание можно применить сегодня в обычной жизни.

Ответь СТРОГО пятью строками оценок и одной строкой замечания, без пояснений:
ЛОГИКА: <число>
РЕАЛИЗМ: <число>
ПРИЁМ: <число>
БЕЗОПАСНОСТЬ: <число>
ПОЛЬЗА: <число>
ЗАМЕЧАНИЕ: <самая важная проблема одним предложением или «нет»>

УРОК:
Ситуация: ${L.situation}
Диалог:
${L.dialog.join('\n')}
Разбор:
${L.breakdown.map(x => '- ' + x).join('\n')}
Фразы: ${L.phrases.join(' | ')}
Задание: ${L.task}
Вопросы: ${L.questions.join(' | ')}`;

export function parseJudge(txt) {
  const t = strip(txt).replace(/ПРИЕМ/g, 'ПРИЁМ'); const s = {};
  for (const c of CRITERIA) { const m = t.match(new RegExp(c + '\\s*[:\\-–—]\\s*(\\d{1,2})', 'i')); if (m) s[c] = Math.max(1, Math.min(10, Number(m[1]))); }
  if (Object.keys(s).length < CRITERIA.length) return null;
  const note = one((t.match(/ЗАМЕЧАНИЕ\s*:\s*(.+)/i) || [])[1] || '');
  const avg = Math.round(CRITERIA.reduce((a, c) => a + s[c], 0) / CRITERIA.length * 10) / 10;
  return { ...s, avg, min: Math.min(...CRITERIA.map(c => s[c])), note: /^нет\.?$/i.test(note) ? '' : note };
}

/* Приёмка: строгая планка и минимальная (для «слабого» урока, который показывается в приложении, но не в канале) */
export const passes = (c, j) => c.ok && j && j.ЛОГИКА >= 7 && j.БЕЗОПАСНОСТЬ >= 8 && j.min >= 6 && total(c, j) >= 7;
export const minimal = (c, j) => c.ok && (!j || (j.ЛОГИКА >= 6 && j.БЕЗОПАСНОСТЬ >= 8));
export const total = (c, j) => Math.round((j ? 0.35 * c.format + 0.65 * j.avg : c.format * 0.8) * 10) / 10;

/* ---------- Генерация с повторами ----------
   llm(prompt, maxTokens, temperature) → Promise<string>. safe(text) → boolean (мат, запрещённые темы).
   Возвращает { lesson, attempts, log } или бросает ошибку, если ни один вариант не прошёл даже минимальную планку. */
export async function generateLessonV2(t, day, { llm, safe = () => true, attempts = 3, judge = true } = {}) {
  const log = []; let best = null, feedback = '';
  for (let i = 0; i < attempts; i++) {
    let raw;
    try { raw = await llm(lessonPromptV2(t, day) + feedback, 2500, 0.7); } catch (e) { log.push({ i, error: 'генерация: ' + e.message }); continue; }
    const c = checkLessonV2(raw, { day, safe });
    let j = null;
    if (c.ok && judge) {
      try { j = parseJudge(await llm(judgePrompt(t, c.lesson), 300, 0.1)); } catch (e) { /* рецензент недоступен — решаем по автопроверке */ }
    }
    const score = total(c, j), entry = { i, hard: c.hard, soft: c.soft, format: c.format, judge: j, score, _raw: raw };
    log.push(entry);
    if (minimal(c, j) && (!best || score > best.score)) best = { c, j, score, pass: passes(c, j) || (!judge && c.ok && c.format >= 8) };
    if (best && best.pass && best.score >= 8) break;
    const fix = [...c.hard, ...c.soft]; if (j && j.note) fix.push('рецензент-психолог: ' + j.note);
    if (j) CRITERIA.filter(k => j[k] < 7).forEach(k => fix.push(`низкая оценка «${k}» (${j[k]})`));
    feedback = fix.length ? `\n\nВАЖНО. Прошлый вариант отклонён. Исправь: ${fix.join('; ')}. Строго соблюдай формат и правила выше.` : '';
  }
  if (!best) {
    const HARD_SAFE = /запрещённые|мат|язык|небезопасн/;
    const fallback = log.filter(l => !l.error && !(l.hard||[]).some(e=>HARD_SAFE.test(e)) && l.format >= 5 && l._raw
      && !(l.judge && l.judge.БЕЗОПАСНОСТЬ < 8)) // если психолог поставил низкую безопасность — не берём даже как fallback
      .sort((a,b) => (b.format||0)-(a.format||0))[0];
    if (fallback) {
      const c2 = checkLessonV2(fallback._raw, { day, safe });
      best = { c: c2, j: null, score: Math.round(fallback.format * 0.6 * 10)/10, pass: false };
    }
  }
  if (!best) throw new Error('урок не прошёл проверку: ' + log.map(l => l.error || (l.hard.join(', ') || (l.judge ? 'оценка ' + l.score + (l.judge.note ? ' — ' + l.judge.note : '') : 'нет оценки'))).join(' | '));
  const { c, j, score, pass } = best;
  return {
    lesson: { ...c.lesson, quality: Math.round(score), qa: { v: 2, format: c.format, judge: j ? Object.fromEntries([...CRITERIA, 'avg', 'note'].map(k => [k, j[k]])) : null, pass, attempts: log.length }, ...(pass ? {} : { weak: true }) },
    log
  };
}
