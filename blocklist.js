/* =====================================================================
   blocklist.js — тематический фильтр «без материалов о военном конфликте».
   Правило нейтральное и одинаковое для всех источников и всех сторон: если материал (новость, анекдот, цитата,
   событие дня) относится к этой теме, он не показывается. Приложение — про общение и развитие, поэтому
   оно не освещает военные конфликты вообще.

   Как править: добавляйте слова в списки ниже (строчными буквами, «ё» писать как «е»).
   • CORE — названия, связанные именно с этим конфликтом. Применяется везде: в новостях, юморе, событиях дня, цитатах, уроках.
   • WIDE — общие «военные» слова. Применяется только к новостям, юмору и цитатам (в уроках про общение
     слова вроде «агрессия» нормальны, а в исторических событиях слова вроде «вторжение» относятся к другим векам).
   Подключён в: tools/build-daily.mjs (сборщик), app.js (приложение), index.html и service-worker.js.
   ===================================================================== */
(function (g) {
  const yo = t => String(t == null ? '' : t).toLowerCase().replace(/ё/g, 'е');
  const W = '[а-яa-z0-9]';                                          // буква или цифра (в JS «\\w» не понимает кириллицу)
  const w = s => '(^|[^а-яa-z0-9])' + s + '([^а-яa-z0-9]|$)';   // слово целиком (границы для кириллицы и латиницы)
  const CORE = [
    'украин', 'донбасс', 'донецк', 'луганск', 'мариупол', 'бахмут', 'херсонск', 'запорожск', 'зеленск', 'спецопераци',
    'специальн' + W + '+ военн' + W + '+ операци', w('сво'), w('всу'), w('днр'), w('лнр'), 'крымск' + W + '+ мост', 'аннекси',
    'ukrain', 'kyiv', 'kiev', 'donbas', 'zelensk', 'special military operation'
  ];
  const WIDE = [
    'вторжен', 'агресси' + W + '* росси', 'росси' + W + '* агресси', 'военн' + W + '+ агресси', 'обстрел', 'лини' + W + '* фронт', w('фронт' + W + '{0,2}'), 'боев' + W + '* действи', 'мобилизац',
    'оккупац', 'контрнаступ', 'военнопленн', 'военн' + W + '+ (конфликт|преступлен|операци)', 'ракетн' + W + '+ (удар|атак|обстрел)', 'сбит' + W + '* (беспилот|ракет|самолет)',
    'атак' + W + '* (беспилот|дрон)', '(беспилот|дрон)' + W + '* (атак|удар|сбит)', 'росси' + W + '* напал',
    'invasion', 'frontline', 'front line', 'shelling', 'airstrike', 'air strike', 'missile (strike|attack)', 'drone (attack|strike)',
    'prisoners? of war', 'occupied territor', 'ceasefire', 'war crimes', 'russia.s war', 'war in '
  ];
  const core = new RegExp(CORE.join('|')), wide = new RegExp(WIDE.join('|'));
  const BLOCK = {
    core: t => core.test(yo(t)),                            // только названия конфликта (узкий фильтр)
    test: t => { const x = yo(t); return core.test(x) || wide.test(x); }   // полный фильтр
  };
  g.BLOCK = BLOCK; if (typeof module !== 'undefined' && module.exports) module.exports = BLOCK;
})(typeof window !== 'undefined' ? window : globalThis);
